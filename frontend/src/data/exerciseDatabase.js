/**
 * 針對 4 週週期化的動態選課
 * W1: 基礎結構 / W2: 肌肥大 / W3: 絕對力量 / W4: 減量恢復
 */
export const selectExercisesForWeek = (muscleGroup, weekNumber, count = 4) => {
    const allExercises = getExercisesForMuscle(muscleGroup);

    switch (weekNumber) {
        case 1: // W1: 偏向 Compound 建立結構
            return [
                ...getExercisesByType(muscleGroup, 'compound').slice(0, Math.ceil(count * 0.6)),
                ...getExercisesByType(muscleGroup, 'isolation').slice(0, Math.floor(count * 0.4))
            ].slice(0, count);

        case 2: // W2: 容量與肌肥大，平均分配
            return [
                ...getExercisesByType(muscleGroup, 'compound').slice(1, 1 + Math.ceil(count * 0.5)),
                ...getExercisesByType(muscleGroup, 'isolation').slice(1, 1 + Math.floor(count * 0.5))
            ].slice(0, count);

        case 3: // W3: 絕對力量，全拿 Compound
            return getExercisesByType(muscleGroup, 'compound').slice(0, count);

        case 4: // W4: Deload，移除高壓動作，補入徒手/輕量隔離
            return [
                ...allExercises.filter(ex => ex.equipment === 'bodyweight' || ex.cns === 'low').slice(0, 2),
                ...getExercisesByType(muscleGroup, 'isolation').slice(0, count - 2)
            ].slice(0, count);

        default:
            return allExercises.slice(0, count);
    }
};

