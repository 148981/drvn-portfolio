// 🈶 英文 → 中文 動作名反查
//   資料來源（既有的中文資料庫，不重造）：
//     ① EXERCISE_TRANSLATION_DICT（中文 → 英文）反轉
//     ② EXERCISE_MASTER_DB 的 nameEn / name 對 name（多半已是中文）
//   正規化：小寫、去掉常見英文後綴（"- Medium Grip" 等）、去多餘空白，
//   讓 "Barbell Bench Press" / "Barbell Bench Press - Medium Grip" 都命中。
// ════════════════════════════════════════════════════════════════════
const hasCJK = (s) => /[一-鿿]/.test(String(s || ''));

const normalizeEn = (s) =>
    String(s || '')
        .toLowerCase()
        .replace(/\s*-\s*(medium|wide|close|narrow)\s*grip/g, '') // 去握距後綴
        .replace(/[^a-z0-9]+/g, ' ')                              // 標點 → 空白
        .trim();

const ENG_TO_ZH_INDEX = (() => {
    const idx = {};
    const put = (en, zh) => {
        if (!en || !zh || !hasCJK(zh)) return;
        const key = normalizeEn(en);
        if (key && !idx[key]) idx[key] = zh;
    };
    // ① 反轉中文→英文字典
    for (const [zh, en] of Object.entries(EXERCISE_TRANSLATION_DICT)) put(en, zh);
    // ② master DB：nameEn / name(英) → name(中)。只在 name 為中文時才當答案。
    for (const ex of EXERCISE_MASTER_DB) {
        if (!hasCJK(ex.name)) continue;          // name 本身是英文的條目跳過（無中文答案）
        put(ex.nameEn, ex.name);
        put(ex.name, ex.name);
    }
    return idx;
})();

